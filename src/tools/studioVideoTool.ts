    /** Runs continuously during playback (and on every scrub), so an overlay's visibility in
     * the live preview tracks the playhead without rebuilding every overlay box on each tick
     * (rebuilding mid-drag would detach the very node a drag is holding, the exact bug already
     * fixed once for selection above). */
    function syncOverlayVisibility() {
      const nowMs = videoEl.currentTime * 1000;
      overlayLayer.querySelectorAll(".studio-video-overlay-box").forEach((node) => {
        const id = node.getAttribute("data-overlay-id");
        const ov = overlays.find((o) => o.id === id);
        if (!ov) return;
        const boxEl = node as HTMLElement;
        boxEl.style.display = nowMs >= ov.startMs && nowMs <= ov.startMs + ov.durationMs ? "" : "none";
        applyOverlayAnimation(boxEl, ov, nowMs);
        // A word-highlight/type-on caption's own content changes continuously as the clip
        // plays, not just its opacity/position, so this rebuilds just that one box's children
        // each tick rather than re-rendering the whole overlay layer (which would detach any
        // box mid-drag).
        if (ov.wordMode && ov.wordMode !== "none" && !(ov.kind === "image")) {
          clear(boxEl);
          for (const node of buildCaptionContent(ov, nowMs)) boxEl.appendChild(typeof node === "string" ? document.createTextNode(node) : node);
        }
      });
    }
    videoEl.addEventListener("timeupdate", syncOverlayVisibility);

    // A smooth entrance animation (a few hundred ms) needs finer-grained updates than
    // "timeupdate" alone provides (that event fires only a few times a second), so this ticks
    // every animation frame instead, but only while the editor is actually the visible view
    // (offsetParent is null once this component's ancestor is hidden by the app's own view
    // switching), so it costs nothing once someone has navigated away from this editor.
    function animTick() {
      if (videoEl.offsetParent !== null) syncOverlayVisibility();
      outerAnimFrameId = requestAnimationFrame(animTick);
    }
