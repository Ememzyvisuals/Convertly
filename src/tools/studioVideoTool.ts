    // Traces an image overlay into an SVG (the same tracing engine as the standalone Vectorize
    // tool and the Design editor's own Vectorize button) and swaps it in place, keeping the
    // overlay's own position, size and timing untouched.
    async function vectorizeOverlayImage(ov: TextOverlay, statusBtn?: HTMLElement) {
      if (ov.kind !== "image" || !ov.imageSrc) return;
      const btn = statusBtn as HTMLButtonElement | undefined;
      const originalLabel = btn?.textContent ?? "Vectorize";
      if (btn) {
        btn.textContent = "Vectorizing...";
        btn.disabled = true;
      }
      showStageProgress("Tracing image into vector paths...", "This can take a few seconds on larger photos.");
      try {
        const { vectorizeImage } = await import("../lib/vectorize");
        const srcBlob = await fetch(ov.imageSrc).then((r) => r.blob());
        const file = new File([srcBlob], "image.png", { type: srcBlob.type || "image/png" });
        const result = await vectorizeImage(file, { colorCount: 16, smoothing: 1, noiseReduction: 4, preserveCorners: true });
        showStageProgress("Finishing up...");
        const svgDataUrl = `data:image/svg+xml;base64,${btoa(unescape(encodeURIComponent(result.svg)))}`;
        const img = new Image();
        await new Promise<void>((resolve, reject) => {
          img.onload = () => resolve();
          img.onerror = () => reject(new Error("Could not load the vectorized image."));
          img.src = svgDataUrl;
        });
        ov.imageSrc = svgDataUrl;
        ov.imageAspect = img.width / Math.max(1, img.height);
        renderOverlayLayer();
        renderProps();
      } catch {
        if (btn) btn.textContent = "Couldn't vectorize, try again";
      } finally {
        hideStageProgress();
        if (btn) {
          btn.disabled = false;
          if (btn.textContent === "Vectorizing...") btn.textContent = originalLabel;
        }
      }
    }

