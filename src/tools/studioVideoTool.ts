interface TextOverlay {
  id: string;
  text: string;
  xPct: number; // center, 0 to 100, relative to the video's real width
  yPct: number; // center, 0 to 100, relative to the video's real height
  sizePct: number; // font size as a percent of the video's real width
  color: string;
  fontId: string;
  bold: boolean;
  kind?: "text" | "sticker" | "image"; // stickers are just emoji glyphs, images are an uploaded photo/asset; all three share the same overlay pipeline
  startMs: number; // when this overlay becomes visible, relative to the clip's own start (0)
  durationMs: number; // how long it stays visible after startMs
  imageSrc?: string; // data URL, image overlays only
  imageAspect?: number; // natural width/height, image overlays only, so the box keeps its shape as sizePct scales it
  entrance?: "none" | "fade" | "pop" | "bounce" | "slide-up"; // how this overlay animates in at startMs, burned into the real export, not just the live preview
  entranceDurationMs?: number;
  isCaption?: boolean; // auto-generated by the Captions component, so it can offer "clear all captions" without touching manual overlays
  templateId?: string; // which Caption Library template this caption was last given, captions only
  uppercase?: boolean;
  bgColor?: string; // a pill/box background behind the text, "" or undefined = none, captions only
  align?: "center" | "left" | "right";
  wordMode?: "none" | "type-on" | "word-highlight"; // how the words *within* this caption reveal over its own time window, captions only
  highlightColor?: string; // word-highlight only: color of the word currently being spoken
  words?: CaptionWord[]; // word-level timing within this caption, captions only, used by type-on/word-highlight
}

