    /** Gives one caption overlay a template's full look in one shot: font, case, color, word
     * animation, position, and entrance, all burned into the real export (see buildOverlayPngs),
     * not just a live-preview skin. Still fully editable afterward, one field at a time, like
     * any other overlay. */
    function applyCaptionTemplate(ov: TextOverlay, tpl: CaptionTemplate) {
      ov.templateId = tpl.id;
      ov.fontId = tpl.fontId;
      ov.bold = tpl.bold;
      ov.uppercase = tpl.uppercase;
      ov.color = tpl.color;
      ov.highlightColor = tpl.highlightColor;
      ov.bgColor = tpl.bgColor;
      ov.sizePct = tpl.sizePct;
      ov.yPct = tpl.yPct;
      ov.align = tpl.align;
      ov.xPct = tpl.align === "left" ? 8 : tpl.align === "right" ? 92 : 50;
      ov.entrance = tpl.animation;
      ov.entranceDurationMs = tpl.animation === "pop" || tpl.animation === "bounce" ? 400 : 300;
      ov.wordMode = tpl.wordMode;
      lastUsedTemplateId = tpl.id;
    }

    // Auto-generates one caption overlay per transcribed phrase, using the clip's own audio,
    // real speech-to-text (see lib/captions.ts), never a stub or placeholder. Runs entirely in
    // the browser: the first use downloads the speech model once (cached by the browser after
    // that), and nothing about the person's video or audio ever leaves the tab. Word-level
    // timing comes back with every phrase, so a word-highlight or typewriter template can track
    // the speaker's actual words rather than just the phrase as a whole.
    async function autoGenerateCaptions() {
      if (captionStatus === "working") return;
      captionStatus = "working";
      renderCaptionsStatus();
      showStageProgress("Loading speech model...", "First use downloads it once; it's cached after that.");
      try {
        const { transcribeVideoToCaptions } = await import("../lib/captions");
        const chunks = await transcribeVideoToCaptions(file, (p) => {
          showStageProgress(
            p.phase === "Transcribing" ? "Transcribing speech..." : p.phase === "Decoding audio" ? "Decoding audio..." : "Loading speech model...",
            typeof p.ratio === "number" ? `${Math.round(p.ratio * 100)}%` : undefined
          );
        });
        if (chunks.length === 0) {
          captionStatus = "error";
          captionErrorMessage = "Couldn't find any speech in this clip's audio.";
        } else {
          const tpl = captionTemplateById(lastUsedTemplateId);
          for (const c of chunks) {
            const ov: TextOverlay = {
              id: uid(),
              text: c.text,
              xPct: 50,
              yPct: 88,
              sizePct: 4.5,
              color: "#ffffff",
              fontId: "anton",
              bold: true,
              kind: "text",
              isCaption: true,
              words: c.words,
              startMs: Math.max(0, c.startSec * 1000),
              durationMs: Math.max(300, (c.endSec - c.startSec) * 1000),
            };
            applyCaptionTemplate(ov, tpl);
            overlays.push(ov);
          }
          captionStatus = "idle";
          captionSubTab = "captions";
          renderOverlayLayer();
          renderOverlayList();
          renderOverlayTracks();
          renderComponentPanel();
        }
      } catch (err) {
        captionStatus = "error";
        captionErrorMessage = err instanceof Error ? err.message : "Something went wrong transcribing this clip.";
        console.error("Auto-captioning failed:", err);
      } finally {
        hideStageProgress();
        renderCaptionsStatus();
      }
    }

