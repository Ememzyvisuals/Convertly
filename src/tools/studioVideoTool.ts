    /** Selecting an overlay/caption/sticker/image on the canvas should also bring its editing
     * controls into view: if some other component's panel is open, switch to the tab matching
     * what was just selected (the shared list/props host all four use), leaving it alone if any
     * of the four is already open. */
    function focusOverlayComponent(ov?: TextOverlay) {
      if (ov?.isCaption && captionSubTab !== "captions") {
        captionSubTab = "captions";
        if (activeComponent === "captions") {
          renderComponentPanel();
          return;
        }
      }
      if (activeComponent === "text" || activeComponent === "captions" || activeComponent === "image" || activeComponent === "stickers") return;
      openComponent(ov?.isCaption ? "captions" : ov?.kind === "image" ? "image" : ov?.kind === "sticker" ? "stickers" : "text");
    }

    function selectOverlay(id: string) {
      selectedId = id;
      renderOverlayLayer();
      focusOverlayComponent(overlays.find((o) => o.id === id));
      renderOverlayList();
      renderProps();
      renderOverlayTracks();
    }

    /** Same selection state as selectOverlay, but toggles the "selected"/"active" classes on
     * the existing overlay boxes and timeline clips instead of rebuilding them, so it is safe
     * to call from a box's or a timeline clip's own pointerdown handler right before (or during)
     * a drag on that exact element. Rebuilding here, as selectOverlay does, would destroy and
     * recreate the very node the pointer just went down on, which throws
     * InvalidStateError the moment the drag then tries to setPointerCapture on it, a real bug
     * caught by testing both the canvas-box drag and, later, the timeline-clip drag. */
    function selectOverlayInPlace(id: string) {
      selectedId = id;
      overlayLayer.querySelectorAll(".studio-video-overlay-box").forEach((node) => {
        node.classList.toggle("selected", node.getAttribute("data-overlay-id") === id);
      });
      overlayTracks.querySelectorAll(".studio-video-layer-row").forEach((node) => {
        node.classList.toggle("active", node.getAttribute("data-overlay-id") === id);
      });
      focusOverlayComponent(overlays.find((o) => o.id === id));
      renderOverlayList();
      renderProps();
    }

