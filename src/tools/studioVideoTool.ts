    /** Applies one overlay's entrance-animation progress to its already-mounted box: the exact
     * same linear ramp math as the ffmpeg filter graph in exportStudioVideo (same start time,
     * same duration, same "fade" alpha ramp / "slide-up" travel distance as a fraction of the
     * frame height), so what plays in the preview is a true match for what gets burned into the
     * exported file, not just a similar-looking approximation. */
    /** How a box is anchored to its own xPct/yPct point: centered by default, or hugging one
     * edge for a left/right-aligned lower-third caption, so the text grows away from its anchor
     * rather than always centering on it. */
    function alignTranslatePrefix(ov: TextOverlay): string {
      if (ov.align === "left") return "translate(0%, -50%)";
      if (ov.align === "right") return "translate(-100%, -50%)";
      return "translate(-50%, -50%)";
    }

    function applyOverlayAnimation(box: HTMLElement, ov: TextOverlay, nowMs: number) {
      const entrance = ov.entrance ?? "none";
      const durMs = Math.max(50, ov.entranceDurationMs ?? 350);
      const p = entrance === "none" ? 1 : Math.max(0, Math.min(1, (nowMs - ov.startMs) / durMs));
      const base = alignTranslatePrefix(ov);
      if (entrance === "fade") {
        box.style.opacity = String(p);
        box.style.transform = base;
      } else if (entrance === "slide-up") {
        box.style.opacity = "1";
        const frameHeightPx = stage.getBoundingClientRect().height || 400;
        const offsetPx = (1 - p) * (frameHeightPx * 0.06);
        box.style.transform = `${base} translateY(${offsetPx}px)`;
      } else if (entrance === "pop") {
        // Same popScale/popOpacity curve buildOverlayPngs bakes into the real export frames.
        box.style.opacity = String(popOpacity(p));
        box.style.transform = `${base} scale(${popScale(p)})`;
      } else if (entrance === "bounce") {
        // Same bounceOffsetPx/bounceOpacity curve buildOverlayPngs bakes into the real export
        // frames; unitPx mirrors the font size the export path scales its own offset by.
        const stageWidthPx = stage.getBoundingClientRect().width || 400;
        const unitPx = (ov.sizePct / 100) * stageWidthPx;
        box.style.opacity = String(bounceOpacity(p));
        box.style.transform = `${base} translateY(${bounceOffsetPx(p, unitPx)}px)`;
      } else {
        box.style.opacity = "1";
        box.style.transform = base;
      }
    }

    /** Builds a caption's on-screen content for one instant in time: plain text normally, or,
     * for a word-highlight/type-on template, a live readout of exactly which words should be
     * visible or lit up right now, using that caption's own per-word timing. Falls back to the
     * whole line whenever a caption has no word timing (e.g. its text was hand-typed or edited
     * in the Transcript tab), so editing never leaves a caption broken. */
    function buildCaptionContent(ov: TextOverlay, nowMs: number): (string | HTMLElement)[] {
      const nowSec = nowMs / 1000;
      const words = ov.words;
      if (ov.wordMode === "word-highlight" && words && words.length > 0) {
        return [
          el(
            "span",
            {},
            words.map((w, i) => {
              const active = nowSec >= w.startSec && nowSec < w.endSec;
              const wordText = ov.uppercase ? w.text.toUpperCase() : w.text;
              return el("span", { style: `color:${active ? ov.highlightColor ?? "#e86f00" : ov.color}` }, [
                i === 0 ? wordText : ` ${wordText}`,
              ]);
            })
          ),
        ];
      }
      if (ov.wordMode === "type-on" && words && words.length > 0) {
        const visible = words.filter((w) => nowSec >= w.startSec).map((w) => (ov.uppercase ? w.text.toUpperCase() : w.text));
        return [visible.join(" ") || " "];
      }
      const text = ov.text || "Text";
      return [ov.uppercase ? text.toUpperCase() : text];
    }

    function renderOverlayLayer() {
      clear(overlayLayer);
      for (const ov of overlays) {
        const font = fontById(ov.fontId);
        const isImage = ov.kind === "image" && ov.imageSrc;
        const nowMsInit = videoEl.currentTime * 1000;
        const box = el(
          "div",
          {
            class: `studio-video-overlay-box${ov.id === selectedId ? " selected" : ""}${isImage ? " studio-video-overlay-box-image" : ""}`,
            "data-overlay-id": ov.id,
          },
          isImage ? [el("img", { src: ov.imageSrc!, draggable: "false", alt: "" })] : buildCaptionContent(ov, nowMsInit)
        );
        box.style.left = `${ov.xPct}%`;
        box.style.top = `${ov.yPct}%`;
        if (isImage) {
          // sizePct here is the overlay's own width as a percent of the frame's width; height
          // follows from the image's real aspect ratio so it never looks squashed.
          box.style.width = `${ov.sizePct}%`;
          box.style.aspectRatio = ov.imageAspect ? String(ov.imageAspect) : "1";
        } else {
          box.style.color = ov.color;
          box.style.fontFamily = font.family;
          box.style.fontWeight = ov.bold ? "700" : "400";
          box.style.fontSize = `${ov.sizePct}cqw`;
          box.style.textAlign = ov.align ?? "center";
          if (ov.bgColor) {
            box.style.background = ov.bgColor;
            box.style.padding = "0.3em 0.6em";
            box.style.borderRadius = "0.35em";
            box.style.whiteSpace = "normal";
          } else {
            box.style.background = "";
            box.style.padding = "";
            box.style.borderRadius = "";
          }
        }
        // Outside its own time window, this overlay stays out of the live preview (it still
        // exists on the timeline and stays editable there), matching what the real export will
        // actually burn into the frame.
        const nowMs = videoEl.currentTime * 1000;
        box.style.display = nowMs >= ov.startMs && nowMs <= ov.startMs + ov.durationMs ? "" : "none";
        applyOverlayAnimation(box, ov, nowMs);
        box.addEventListener("pointerdown", (e) => {
          e.preventDefault();
          // Selecting must not rebuild the overlay boxes here, the pointer is down on this
          // exact element and a full remount would detach it mid-drag (real bug caught via
          // testing: setPointerCapture threw InvalidStateError because this node had already
          // been replaced by the time it ran).
          selectOverlayInPlace(ov.id);
          box.setPointerCapture(e.pointerId);
          const onMove = (ev: PointerEvent) => {
            const rect = overlayLayer.getBoundingClientRect();
            if (rect.width === 0 || rect.height === 0) return;
            ov.xPct = Math.max(0, Math.min(100, ((ev.clientX - rect.left) / rect.width) * 100));
            ov.yPct = Math.max(0, Math.min(100, ((ev.clientY - rect.top) / rect.height) * 100));
            box.style.left = `${ov.xPct}%`;
            box.style.top = `${ov.yPct}%`;
          };
          const onUp = () => {
            window.removeEventListener("pointermove", onMove);
            window.removeEventListener("pointerup", onUp);
          };
          window.addEventListener("pointermove", onMove);
          window.addEventListener("pointerup", onUp);
        });
        overlayLayer.appendChild(box);
      }
    }

