    // ---------------- Filmstrip (real extracted frames, not a flat color bar) ----------------

    async function buildFilmstrip() {
      if (duration <= 0) return;
      clear(filmstrip);
      filmstripLoading.style.display = "flex";
      const wasPlaying = !videoEl.paused;
      videoEl.pause();
      const resumeTime = videoEl.currentTime;

      const trackWidth = trimTrack.getBoundingClientRect().width || 760;
      const tileWidth = 84;
      const count = Math.max(6, Math.min(16, Math.round(trackWidth / tileWidth)));

      const canvas = document.createElement("canvas");
      const aspect = (videoEl.videoWidth || 16) / (videoEl.videoHeight || 9);
      canvas.width = 160;
      canvas.height = Math.round(160 / aspect);
      const ctx = canvas.getContext("2d");

      const seekTo = (t: number): Promise<void> =>
        new Promise((resolve) => {
          const onSeeked = () => {
            videoEl.removeEventListener("seeked", onSeeked);
            resolve();
          };
          videoEl.addEventListener("seeked", onSeeked);
          videoEl.currentTime = t;
        });

      for (let i = 0; i < count; i++) {
        const t = Math.min(duration - 0.05, Math.max(0, ((i + 0.5) / count) * duration));
        try {
          await seekTo(t);
          if (ctx) ctx.drawImage(videoEl, 0, 0, canvas.width, canvas.height);
          const dataUrl = canvas.toDataURL("image/jpeg", 0.6);
          const img = el("img", { class: "studio-video-filmstrip-tile", alt: "" }) as HTMLImageElement;
          img.src = dataUrl;
          filmstrip.appendChild(img);
          // The filter swatches need one representative real frame too (a <video> blob URL
          // can't be used as a CSS background-image), so this reuses the middle filmstrip
          // tile already decoded here rather than seeking again just for that.
          if (i === Math.floor(count / 2)) filterThumbUrl = dataUrl;
        } catch {
          // A frame that fails to decode just leaves a gap tile rather than breaking the whole strip.
        }
      }

      await seekTo(resumeTime);
      if (wasPlaying) void videoEl.play().catch(() => {});
      filmstripLoading.style.display = "none";
    }

    // ---------------- Trim track (drag to pick the exported range) ----------------

    function pctFromClientX(clientX: number): number {
      const rect = trimTrack.getBoundingClientRect();
      if (rect.width === 0) return 0;
      return Math.max(0, Math.min(100, ((clientX - rect.left) / rect.width) * 100));
    }

    function renderTrim() {
      if (duration <= 0) return;
      const startPct = (trimStart / duration) * 100;
      const endPct = (trimEnd / duration) * 100;
      trimStartHandle.style.left = `${startPct}%`;
      trimEndHandle.style.left = `${endPct}%`;
      trimRange.style.left = `${startPct}%`;
      trimRange.style.width = `${Math.max(0, endPct - startPct)}%`;
      // The parts of the filmstrip outside the selected range are dimmed, matching how a
      // real timeline shows what will and won't make it into the export.
      maskLeft.style.width = `${startPct}%`;
      maskRight.style.width = `${100 - endPct}%`;
      const readout = trimLabels.querySelector(".studio-video-trim-readout");
      if (readout) readout.textContent = `${formatTime(trimStart)} to ${formatTime(trimEnd)} (${formatTime(trimEnd - trimStart)})`;
      renderOverlayTracks();
    }

